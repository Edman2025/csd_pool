#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="${CSD_POOL_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
PASS=0
FAIL=0

ok() {
  PASS=$((PASS + 1))
  printf 'ok: %s\n' "$1"
}

fail() {
  FAIL=$((FAIL + 1))
  printf 'fail: %s\n' "$1" >&2
}

require_file() {
  local path="$1"
  if [[ -f "$ROOT_DIR/$path" ]]; then
    ok "file exists: $path"
  else
    fail "missing file: $path"
  fi
}

require_executable() {
  local path="$1"
  if [[ -x "$ROOT_DIR/$path" ]]; then
    ok "executable exists: $path"
  else
    fail "missing executable: $path"
  fi
}

require_text() {
  local path="$1"
  local pattern="$2"
  if grep -Fq "$pattern" "$ROOT_DIR/$path"; then
    ok "$path contains $pattern"
  else
    fail "$path missing $pattern"
  fi
}

require_no_regex() {
  local path="$1"
  local pattern="$2"
  local label="$3"
  if grep -Eq "$pattern" "$ROOT_DIR/$path"; then
    fail "$label"
  else
    ok "$label"
  fi
}

check_release_manifest_coverage() {
  local output
  if output="$(python3 - "$ROOT_DIR/ops/bin/csd-pool-build-release.sh" "$ROOT_DIR/ops/bin/csd-pool-verify.sh" 2>&1 <<'PY'
import pathlib
import sys

build_path = pathlib.Path(sys.argv[1])
verify_path = pathlib.Path(sys.argv[2])
build_text = build_path.read_text(encoding="utf-8")
verify_text = verify_path.read_text(encoding="utf-8")

missing = []
in_manifest = False
for raw_line in build_text.splitlines():
    line = raw_line.strip()
    if line == 'cat >"$STAGING_DIR/RELEASE-MANIFEST.txt" <<MANIFEST':
        in_manifest = True
        continue
    if in_manifest and line == "MANIFEST":
        break
    if not in_manifest or "=" not in raw_line:
        continue
    key, value = raw_line.split("=", 1)
    if value.startswith("ops/bin/") or value.startswith(".github/"):
        entry = f"{key}={value}"
        if entry not in verify_text:
            missing.append(entry)

if missing:
    print("missing release verifier manifest coverage:")
    for entry in missing:
        print(entry)
    raise SystemExit(1)
PY
  )"; then
    ok "release verifier covers every release manifest ops/bin and workflow entry"
  else
    printf '%s\n' "$output" >&2
    fail "release verifier covers every release manifest ops/bin and workflow entry"
  fi
}

check_release_manifest_coverage

